function fill_template(src) {
	var template = Handlebars.templates['project-template'](src);
	document.querySelector('#output').innerHTML = template;

}



/*----------PHOTOS-------------*/

function show_image(src) {
	var img = document.createElement('img');
	img.src = src
	img.setAttribute('class', 'responsive');
	img.setAttribute('id', 'img');
	
	document.body.appendChild(img);
}

function remove_image() {
	let images = document.getElementById('img');
	console.log(images)
	if (images != null){
 		images.remove()
 	}
}

function photos() {
var links = document.querySelectorAll('a.image-link');

for(let i=0; i < links.length; i++){
    let url = links[i].dataset.url

    links[i].addEventListener('click', function(){
    	remove_image();
    	show_image(url)
    }, false);
   
}}



